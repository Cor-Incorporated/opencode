// Packet A3b (review follow-up): `cor-local`'s options.baseURL/apiKey are
// `{env:COR_LOCAL_BASE_URL}`/`{env:COR_LOCAL_API_KEY}`
// (packages/guardrails/{managed,profile}/opencode.json). `{env:VAR}`
// substitution (packages/opencode/src/config/variable.ts) resolves an unset
// var to "" unconditionally -- it never errors -- so an unset
// COR_LOCAL_BASE_URL would splice "" into baseURL and every cor-local call
// would fail with `TypeError: Invalid URL` well past `opencode models`
// (which never touches the provider client).
//
// This module is imported by `bin/opencode-guardrails`, the one entry point
// guaranteed to run before every `opencode-guardrails` invocation -- managed
// deploy, the live wrapper, and a direct `opencode-guardrails` call alike --
// so the defaulting lives here, not in the shell wrapper generated by
// scripts/local-dev-deploy.sh (that generated wrapper is not the only entry
// point, and it goes stale between a `git pull` and the next
// `local:deploy`/`local:fix`). Split into its own file (rather than inlined
// in the bin script) so it can be `import`-ed and unit tested without
// triggering the bin script's unconditional `spawnSync` of opencode itself.
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { spawnSync } from "node:child_process"

export const DEFAULT_COR_LOCAL_BASE_URL = "http://127.0.0.1:18082/v1"
export const DEFAULT_COR_LOCAL_KEY_FILE = path.join(os.homedir(), "cluster-ops", "cor-local.key")

// `{env:VAR}` is spliced into the JSON config text as raw, unescaped bytes
// (variable.ts:36-38 -- unlike `{file:...}`, which goes through
// `JSON.stringify(...).slice(1, -1)`), so a key containing `"`, `\`, or a
// newline would corrupt the whole config text and take down every provider,
// not just cor-local. Only a single line of this conservative charset is
// accepted; anything else is ignored with a warning that never echoes the
// value.
export const VALID_KEY_RE = /^[A-Za-z0-9._~+/=-]+$/

const WINDOWS_KEY_ACL = `
$ErrorActionPreference = 'Stop'
$acl = Get-Acl -LiteralPath $env:OPENCODE_COR_LOCAL_ACL_PATH
$rules = $acl.GetAccessRules($true, $true, [System.Security.Principal.SecurityIdentifier])
$allowed = @($rules | Where-Object { $_.AccessControlType -eq [System.Security.AccessControl.AccessControlType]::Allow } | ForEach-Object { $_.IdentityReference.Value })
@{
  user = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
  owner = $acl.GetOwner([System.Security.Principal.SecurityIdentifier]).Value
  allow = $allowed
} | ConvertTo-Json -Compress
`

/** Decode the ACL probe without accepting unreadable, null-DACL or foreign-principal access. */
export function privateWindowsKeyAcl(result) {
  if (!result || result.error || result.status !== 0 || typeof result.stdout !== "string") return false
  let acl
  try {
    acl = JSON.parse(result.stdout)
  } catch {
    return false
  }
  if (!acl || typeof acl !== "object" || typeof acl.user !== "string" || !/^S-\d+-\d+(?:-\d+)+$/.test(acl.user))
    return false
  if (!Array.isArray(acl.allow) || acl.allow.length === 0) return false
  const principals = new Set([acl.user, "S-1-5-18", "S-1-5-32-544"])
  return principals.has(acl.owner) && acl.allow.every((sid) => typeof sid === "string" && principals.has(sid))
}

function windowsKeyFilePrivate(filePath) {
  const powershell = path.join(
    process.env.SystemRoot || "C:\\Windows",
    "System32",
    "WindowsPowerShell",
    "v1.0",
    "powershell.exe",
  )
  return privateWindowsKeyAcl(
    spawnSync(powershell, ["-NoLogo", "-NoProfile", "-NonInteractive", "-Command", WINDOWS_KEY_ACL], {
      env: { ...process.env, OPENCODE_COR_LOCAL_ACL_PATH: path.resolve(filePath) },
      encoding: "utf8",
      timeout: 5_000,
      maxBuffer: 65_536,
      windowsHide: true,
      shell: false,
    }),
  )
}

/**
 * Reads and validates a cor-local API key from `filePath`. Returns the key
 * (no trailing newline) on success, or `undefined` if the file is missing,
 * unreadable, not owner-only permissions, or does not contain exactly one
 * valid-charset line. Invalid-format cases log a warning to stderr that
 * never includes the file's contents.
 */
export function loadCorLocalKeyFromFile(filePath, { warn = (msg) => console.error(msg) } = {}) {
  let stat
  try {
    stat = fs.statSync(filePath)
  } catch {
    return undefined
  }
  if (!stat.isFile()) return undefined
  // Windows mode bits do not describe its ACL. Both checks reject unprivileged access before reading the key.
  const secure = process.platform === "win32" ? windowsKeyFilePrivate(filePath) : (stat.mode & 0o077) === 0
  if (!secure) {
    warn("cor-local: key file ignored (invalid format)")
    return undefined
  }
  let raw
  try {
    raw = fs.readFileSync(filePath, "utf8")
  } catch {
    return undefined
  }
  const lines = raw.split(/\r\n|\r|\n/)
  // Exactly one content line, optionally followed by one trailing newline
  // (split() on a string ending in "\n" yields a trailing "" element).
  const trailingOk = lines.length === 1 || (lines.length === 2 && lines[1] === "")
  const first = lines[0]
  if (!trailingOk || !VALID_KEY_RE.test(first)) {
    warn("cor-local: key file ignored (invalid format)")
    return undefined
  }
  return first
}

/**
 * Mutates `env` (defaults to `process.env`) in place: defaults
 * `COR_LOCAL_BASE_URL` to the Mac Studio router's local address when unset
 * or empty, and -- when `COR_LOCAL_API_KEY` is unset or empty -- reads a key
 * from `COR_LOCAL_KEY_FILE` (or the default `~/cluster-ops/cor-local.key`)
 * if it validates. Never overrides a caller-supplied, non-empty value for
 * either variable.
 */
export function applyCorLocalDefaults(env = process.env, { warn } = {}) {
  env.COR_LOCAL_BASE_URL ||= DEFAULT_COR_LOCAL_BASE_URL
  if (!env.COR_LOCAL_API_KEY) {
    const keyFile = env.COR_LOCAL_KEY_FILE || DEFAULT_COR_LOCAL_KEY_FILE
    const key = loadCorLocalKeyFromFile(keyFile, warn !== undefined ? { warn } : undefined)
    if (key) env.COR_LOCAL_API_KEY = key
  }
}
